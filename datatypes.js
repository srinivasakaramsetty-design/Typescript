// STRING DATA TYPE
// Used to store text values (names, city, etc.)
var FNAME = "Srinivas";
var city = "Hyderabad";
console.log(FNAME);
console.log(city);
// NUMBER DATA TYPE
// Used to store numeric values (integers or decimals)
var num1 = 100;
var num2 = 200;
console.log(num1);
console.log(num2);
// BOOLEAN DATA TYPE
// Used to store true or false values
var isMarried = false;
console.log(isMarried);
var isEmployed = true;
console.log(isEmployed);
// NULL DATA TYPE
// Represents intentional absence of value
var myVar = null;
console.log(myVar);
// UNDEFINED DATA TYPE
// Variable declared but not assigned any value
var anotherVar = undefined;
console.log(anotherVar);
// ANY DATA TYPE
// Can hold any type of value (string, number, boolean)
// Not recommended because it disables type checking
var value = "Hello"; // string
value = 100; // number
value = true; // boolean
console.log(value);
// ARRAY (STRING ARRAY)
// Used to store multiple string values
var names = ["Srinivas", "Tester"];
console.log(names);
// ARRAY (NUMBER ARRAY)
// Used to store multiple number values
var numbers = [1, 2, 3];
console.log(numbers);
// TUPLE DATA TYPE
// Fixed size array with different data types
var user = ["Srinivas", 25];
console.log(user);
var userName = "Srinivas";
console.log(userName);
var emp = {
    name: "Srinivas",
    id: 101
};
console.log(emp);
var testResult = "PASS";
console.log(testResult);
